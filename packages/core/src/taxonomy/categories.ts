/** Every category code, in taxonomy order. */
export const CATEGORY_CODES: readonly string[] = Object.freeze(CATEGORIES.map((c) => c.code));

const BY_CODE = new Map<string, BenchmarkCategory>(CATEGORIES.map((c) => [c.code, c]));

/** Category for a code, or undefined when the code is unknown. */
export function categoryByCode(code: string | null | undefined): BenchmarkCategory | undefined {
  return code ? BY_CODE.get(code) : undefined;
}

/** Code used when no keyword matches and no vendor memory applies. */
export const UNCLASSIFIED_CODE = 'MISC';

/**
 * Categories with no comparable reference in v1. The BENCHMARK layer is skipped for these and
 * the expected price rests on the contract and budget layers only.
 */
export const NON_BENCHMARKABLE_CODES: ReadonlySet<string> = Object.freeze(
  new Set(CATEGORIES.filter((c) => !c.comparableDefault).map((c) => c.code)),
);

/** Whether a category may enter the BENCHMARK layer at all. */
export function isBenchmarkable(code: string | null | undefined): boolean {
  const cat = categoryByCode(code);
  return cat ? cat.comparableDefault && cat.layers.includes('K') : false;
}

/** Whether a category may use a layer. */
export function hasLayer(code: string | null | undefined, layer: CategoryLayer): boolean {
  return categoryByCode(code)?.layers.includes(layer) ?? false;
}
