/**
 * The line taxonomy of `docs/taxonomy.md`: 43 category codes with the keyword lists used to
 * map an invoice line, quote partida or certification item to a category.
 *
 * The category decides which expected-price layers apply (`C` contract, `B` approved budget,
 * `K` benchmark, `H` own history), which unit a quantity is converted to, and whether the
 * BENCHMARK layer may be used at all. This module is data only; the matching lives in
 * `classify.ts`.
 *
 * The same rows are seeded into `public.benchmark_categories` by
 * `supabase/migrations/0010_m4_extension.sql`; keep the two identical.
 */

/** Expected-price layer a category can feed. */
export type CategoryLayer = 'C' | 'B' | 'K' | 'H';

/** One taxonomy category. */
export interface BenchmarkCategory {
  /** Stable code, e.g. `PAINT_INT`. */
  code: string;
  labelEs: string;
  labelCa: string;
  labelEn: string;
  /** Spanish keywords, as written in the documents (accents and case are normalised on use). */
  keywordsEs: string[];
  /** Catalan keywords. */
  keywordsCa: string[];
  /** Unit the quantity is expected in, or null when the category has no natural unit. */
  unit: string | null;
  /** Layers that may contribute an expectation for this category. */
  layers: CategoryLayer[];
  /**
   * `false` marks the category as non-benchmarkable in v1: the BENCHMARK layer is skipped and
   * the report prints "no comparable benchmark". CONTRACT and BUDGET still apply.
   */
  comparableDefault: boolean;
  /** Neutral note on comparability or on how the category is handled. */
  notes: string | null;
}

